// Mensagens das fontes que chegam atrasadas (como histórico) viram fila sozinhas: node test/teste-atrasadas.js
import assert from 'node:assert/strict'
import fs from 'node:fs'
process.env.DATA_DIR = '/tmp/gr-teste-atrasadas'; fs.rmSync(process.env.DATA_DIR, { recursive: true, force: true })
const { q, um, todos } = await import('../src/db.js')
;(await import('../src/contexto.js')).entrarConta(1)
const { carregarConfig, atualizarConfig } = await import('../src/config.js')
const P = await import('../src/pipeline.js')
const { EXEMPLOS } = await import('../src/exemplos.js')
await carregarConfig()
await atualizarConfig({ ia: { modo: 'desligado' }, fipe: { consultar: false } })
P.usarWhatsAppDeTeste({ conectado: () => true, baixarBruto: async () => null, baixarMidia: async () => null, baixarFotos: async () => [null] })
await P.garantirGrupo('f@g.us', 'Fonte'); await q("UPDATE repasse.grupos SET fonte = true, arquivado = false WHERE jid = 'f@g.us'")
await P.garantirGrupo('outro@g.us', 'Não é fonte'); await q("UPDATE repasse.grupos SET arquivado = false WHERE jid = 'outro@g.us'")
await P.recarregarGrupos()
const h = (min) => Date.now() - min * 60e3
// chegaram atrasadas (historico: true): 2 da fonte de horas atrás, 1 recente demais (fica para o ao vivo), 1 de grupo que não é fonte
await P.receberMensagem({ chatJid: 'f@g.us', remetente: { id: 'a' }, texto: EXEMPLOS[0], id: 'm1', ts: h(300), historico: true })
await P.receberMensagem({ chatJid: 'f@g.us', remetente: { id: 'b' }, texto: EXEMPLOS[1], id: 'm2', ts: h(120), historico: true })
await P.receberMensagem({ chatJid: 'f@g.us', remetente: { id: 'c' }, texto: EXEMPLOS[2], id: 'm3', ts: h(1), historico: true })
await P.receberMensagem({ chatJid: 'outro@g.us', remetente: { id: 'd' }, texto: EXEMPLOS[5], id: 'm4', ts: h(60), historico: true })
await P.receberMensagem({ chatJid: 'f@g.us', remetente: { id: 'e' }, texto: EXEMPLOS[3], id: 'm5', ts: h(26 * 60), historico: true })
assert.equal((await todos('SELECT 1 FROM repasse.anuncios')).length, 0, 'histórico não processa na hora')
await P.processarAtrasadas()
const an = await todos('SELECT modelo FROM repasse.anuncios ORDER BY modelo')
assert.deepEqual(an.map(a => a.modelo), ['Civic', 'Onix'], 'só fonte, últimas 24 h, com mais de 3 min')
assert.equal((await um("SELECT processado FROM repasse.mensagens WHERE id = 'm3'")).processado, false)
await P.processarAtrasadas()
assert.equal((await todos('SELECT 1 FROM repasse.anuncios')).length, 2, 'não duplica')
P.usarWhatsAppDeTeste({ conectado: () => false })
await q("UPDATE repasse.mensagens SET processado = false WHERE id = 'm1'"); await P.processarAtrasadas()
assert.equal((await todos('SELECT 1 FROM repasse.anuncios')).length, 2, 'desconectado: espera')
// KM máx. negativo salvo sem querer: ignorado nos filtros e limpo ao salvar
const { cfg, atualizarConfig: atu } = await import('../src/config.js')
const { avaliarFiltros } = await import('../src/formatter.js')
assert.deepEqual(avaliarFiltros({ pontos: 10, km: 45000, alertas: [], preco: 50000, anoModelo: 2020, textoOriginal: '' }, { ...cfg(), filtros: { ...cfg().filtros, kmMax: -21, exigirFoto: false } }, { temMidia: true }).filter(m => m.startsWith('km')), [], 'km negativo ignorado')
await atu({ filtros: { kmMax: -21 } }); assert.equal(cfg().filtros.kmMax, null, 'negativo vira vazio ao salvar')

// recuperação: anúncio filtrado só por "km > -21" é reprocessado a partir da mensagem original
P.usarWhatsAppDeTeste({ conectado: () => true, baixarBruto: async () => null, baixarMidia: async () => null, baixarFotos: async () => [null] })
await q('DELETE FROM repasse.anuncios')
await P.receberMensagem({ chatJid: 'f@g.us', remetente: { id: 'z', nome: 'Z' }, texto: EXEMPLOS[2], id: 'k1', ts: h(30), historico: true })
await q("UPDATE repasse.mensagens SET processado = true WHERE id = 'k1'")
await q(`INSERT INTO repasse.anuncios (id, conta_id, status, motivos, dados, grupo_jid, remetente_id, texto, numero_fila)
  VALUES (gen_random_uuid(), 1, 'filtrado', '["km > -21"]'::jsonb, $1::jsonb, 'f@g.us', 'z', 'x', 999)`, [JSON.stringify({ textoOriginal: EXEMPLOS[2] })])
await q(`INSERT INTO repasse.anuncios (id, conta_id, status, motivos, dados, grupo_jid, remetente_id, texto, numero_fila)
  VALUES (gen_random_uuid(), 1, 'filtrado', '["km > -21"]'::jsonb, '{"textoOriginal":"mensagem que já não existe"}'::jsonb, 'f@g.us', 'y', 'x', 998)`)
await q("DELETE FROM repasse.kv WHERE chave LIKE 'v071-km:%'"); await P.recuperarFiltradosPorKm()
const rec = await todos('SELECT status, modelo, numero_fila, motivos FROM repasse.anuncios ORDER BY numero_fila')
assert.equal(rec.filter(r => JSON.stringify(r.motivos).includes('km >')).length, 0, 'nenhum filtrado por km')
assert.ok(rec.some(r => r.modelo === 'Strada' && r.numero_fila !== 999), 'reprocessado da mensagem original')
assert.ok(rec.some(r => r.numero_fila === 998 && r.status === 'pendente'), 'sem mensagem: volta para a fila')
await q("UPDATE repasse.anuncios SET status = 'filtrado', motivos = '[\"km > -21\"]'::jsonb WHERE numero_fila = 998")
await P.recuperarFiltradosPorKm()
assert.equal((await um("SELECT status FROM repasse.anuncios WHERE numero_fila = 998")).status, 'filtrado', 'roda uma vez só')
console.log('✓ atrasadas: mensagens que chegam depois viram fila sozinhas, sem duplicar')
process.exit(0)
